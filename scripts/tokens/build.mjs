#!/usr/bin/env node
/**
 * Figma → CSS. Reads tokens/figma/variables.json (written by the "Publish tokens" plugin in the
 * SKO DS file, figma-plugin/) and writes tokens/generated/*.css. Nothing in tokens/generated/ is
 * edited by hand: change the value in Figma and publish again.
 *
 *   node scripts/tokens/build.mjs           write the files
 *   node scripts/tokens/build.mjs --check   exit 1 if the files are not what the JSON gives
 *
 * What maps where:
 *   1. SKO-Semantics 🎨 colours   → colors.css      --color-* (the Web code syntax set in Figma)
 *     modes SKO / Gold / Red / Studio × Light / Dark → :root, [data-theme], [data-skin], [data-direction]
 *   2. Responsive 📐 Radius/*      → radius.css      --sk-radius-*
 *   2. Responsive 📐 Spacing/*, Container/* → spacing.css  --sk-space-*, --sk-container-*
 *   2. Responsive 📐 Type/* + text styles   → typography.css  --sk-type-* and .sk-text-* classes
 *   3. Motion                      → motion.css      --motion-*
 * Responsive modes follow lib/useBreakpoint.ts: Desktop by default, Tablet ≤ 1024, Mobile ≤ 768,
 * and a forced device preview ([data-device]) last so it wins over the window width.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const SOURCE = path.join(root, "tokens/figma/variables.json");
const OUT = path.join(root, "tokens/generated");

const data = JSON.parse(fs.readFileSync(SOURCE, "utf8"));
const col = (prefix) => {
  const c = data.collections.find((x) => x.name.startsWith(prefix));
  if (!c) throw new Error(`collection "${prefix}…" missing from ${SOURCE}`);
  return c;
};

const header = (what) =>
  `/* GENERATED by scripts/tokens/build.mjs from tokens/figma/variables.json — do not edit.\n` +
  `   Source: Figma SKO Design System (${data.fileKey}), ${what}.\n` +
  `   To change a value, change it in Figma and press Publish tokens. */\n`;
const block = (selector, lines) => (lines.length ? `${selector} {\n${lines.map((l) => `  ${l}`).join("\n")}\n}\n` : "");

/* ---- Colours ---------------------------------------------------------------------------- */
function colors() {
  const c = col("1.");
  // The CSS name is the Web code syntax from Figma; a token without one follows the same rule
  // (DS "text/on-inverse" → --color-text-on-inverse).
  const name = (v) => (v.web ? v.web.replace(/^var\((--[^)]+)\)$/, "$1") : `--color-${v.name.replace(/\//g, "-")}`);
  const tokens = c.variables.filter((v) => v.type === "COLOR");
  const mode = (m) => new Map(tokens.map((v) => [name(v), v.values[m]]));
  const decl = (map, keys) => keys.map((k) => `${k}: ${map.get(k)};`);
  const diff = (a, b) => [...a.keys()].filter((k) => a.get(k) !== b.get(k));

  const L = mode("SKO Light");
  const D = mode("SKO Dark");
  const skins = ["Gold", "Red"];
  const all = [...L.keys()];
  // [data-skin="teal"] forces SKO inside another skin: every token a skin changes, at its SKO value.
  const skinKeys = (base, theme) => all.filter((k) => skins.some((s) => mode(`${s} ${theme}`).get(k) !== base.get(k)));

  let css = header("collection 1. SKO-Semantics 🎨, colour tokens");
  css += `\n/* SKO Light. [data-theme="light"] is a light island inside the dark theme (the certificate sheet). */\n`;
  css += block(`:root,\n[data-theme="light"]`, decl(L, all));
  css += `\n/* Light skins: only what the skin changes. */\n`;
  css += block(`[data-skin="teal"]`, decl(L, skinKeys(L, "Light")));
  for (const s of skins) {
    const m = mode(`${s} Light`);
    css += "\n" + block(`[data-skin="${s.toLowerCase()}"]`, decl(m, diff(m, L)));
  }
  css += `\n/* SKO Dark */\n`;
  css += block(`[data-theme="dark"]`, decl(D, all));
  css += `\n/* Dark skins */\n`;
  css += block(`[data-skin="teal"][data-theme="dark"]`, decl(D, skinKeys(D, "Dark")));
  for (const s of skins) {
    const m = mode(`${s} Dark`);
    css += "\n" + block(`[data-skin="${s.toLowerCase()}"][data-theme="dark"]`, decl(m, diff(m, D)));
  }
  // Studio is a direction in the prototype (html[data-direction="studio"]), not a skin attribute.
  const SL = mode("Studio Light");
  const SD = mode("Studio Dark");
  css += `\n/* Studio Light (html[data-direction="studio"]): what it changes from SKO Light. */\n`;
  css += block(`[data-direction="studio"]:not([data-theme="dark"])`, decl(SL, diff(SL, L)));
  css += `\n/* Studio Dark: also every nested dark region, so a Studio page never mixes in SKO Dark's greys. */\n`;
  css += block(`html[data-direction="studio"][data-theme="dark"],\nhtml[data-direction="studio"] [data-theme="dark"]`, decl(SD, diff(SD, D)));
  return css;
}

/* ---- Responsive helpers ------------------------------------------------------------------ */
const R = () => col("2.");
const px = (n) => `${n}px`;
const rem = (n) => `${+(n / 16).toFixed(4)}rem`;
// One var per mode: Desktop in :root, Tablet/Mobile under the prototype's breakpoints (only what
// changes), then the forced device preview with every mode-aware var.
function responsive(vars, cssName, unit) {
  const val = (v, m) => unit(v.values[m]);
  const changes = (m, ref) => vars.filter((v) => v.values[m] !== v.values[ref]);
  const aware = vars.filter((v) => new Set(Object.values(v.values)).size > 1);
  const lines = (list, m) => list.map((v) => `${cssName(v)}: ${val(v, m)};`);
  let css = block(":root", lines(vars, "Desktop"));
  const tablet = changes("Tablet", "Desktop");
  const mobile = changes("Mobile", "Desktop");
  if (tablet.length) css += `@media screen and (max-width: 1024px) {\n${block(":root", lines(tablet, "Tablet")).replace(/^/gm, "  ")}}\n`;
  if (mobile.length) css += `@media screen and (max-width: 768px) {\n${block(":root", lines(mobile, "Mobile")).replace(/^/gm, "  ")}}\n`;
  for (const m of ["Desktop", "Tablet", "Mobile"]) css += block(`[data-device="${m.toLowerCase()}"]`, lines(aware, m));
  return css;
}

function radius() {
  // The role tokens (Radius/control, Radius/card…), not the fixed-* scale they alias.
  const vars = R().variables.filter((v) => /^Radius\/(?!fixed-)/.test(v.name));
  return header("collection 2. Responsive 📐, Radius/* roles") + "\n" +
    responsive(vars, (v) => `--sk-radius-${v.name.split("/")[1]}`, px);
}

function spacing() {
  const vars = R().variables.filter((v) => /^(Spacing|Container)\//.test(v.name));
  const name = (v) => {
    const [group, key] = v.name.split("/");
    return group === "Spacing" ? `--sk-space-${key}` : `--sk-container-${key}`;
  };
  return header("collection 2. Responsive 📐, Spacing/* and Container/*") + "\n" + responsive(vars, name, px);
}

function typography() {
  const vars = R().variables.filter((v) => /^Type\/(size|line-height)\//.test(v.name));
  const name = (v) => `--sk-type-${v.name.split("/")[1]}-${v.name.split("/")[2]}`;
  let css = header("collection 2. Responsive 📐 Type/*, and the 47 text styles");
  css += "\n/* Sizes in rem, so the browser's own text size scales the ramp; --sk-font-scale multiplies on top. */\n";
  css += responsive(vars, name, rem);
  const weight = { Regular: 400, Medium: 500, SemiBold: 600, Semibold: 600, Bold: 700 };
  css += "\n/* One class per DS text style: .sk-text-{style}-{weight}. */\n";
  for (const s of data.textStyles) {
    const [style, w] = s.name.split("/");
    const family = s.bound.fontFamily === "Type/family/display" ? "--sk-font-display" : "--sk-font-body";
    const size = `var(--sk-type-size-${s.bound.fontSize.split("/")[2]})`;
    const lh = `var(--sk-type-line-height-${s.bound.lineHeight.split("/")[2]})`;
    const props = [
      `font-family: var(${family});`,
      `font-weight: ${weight[s.fontStyle]};`,
      `font-size: calc(${size} * var(--sk-font-scale, 1));`,
      `line-height: calc(${lh} * var(--sk-font-scale, 1));`,
    ];
    if (s.letterSpacing.value) props.push(`letter-spacing: ${+(s.letterSpacing.value / 100).toFixed(4)}em;`);
    if (s.textCase === "UPPER") props.push("text-transform: uppercase;");
    css += block(`.sk-text-${style}-${w.toLowerCase()}`, props);
  }
  return css;
}

function motion() {
  const c = col("3.");
  const unit = (v) => {
    const x = v.values[c.modes[0]];
    if (v.name.startsWith("duration/")) return `${x}ms`;
    if (v.name.startsWith("distance/")) return `${x}px`;
    return x;
  };
  const name = (v) => (v.web ? v.web.replace(/^var\((--[^)]+)\)$/, "$1") : `--motion-${v.name.replace(/\//g, "-")}`);
  return header("collection 3. Motion") + "\n" + block(":root", c.variables.map((v) => `${name(v)}: ${unit(v)};`));
}

const files = { "colors.css": colors(), "radius.css": radius(), "spacing.css": spacing(), "typography.css": typography(), "motion.css": motion() };

if (process.argv.includes("--check")) {
  const stale = Object.entries(files).filter(([f, css]) => {
    const p = path.join(OUT, f);
    return !fs.existsSync(p) || fs.readFileSync(p, "utf8") !== css;
  });
  if (stale.length) {
    console.error(`tokens/generated is out of date: ${stale.map(([f]) => f).join(", ")}. Run node scripts/tokens/build.mjs`);
    process.exit(1);
  }
  console.log("tokens/generated matches tokens/figma/variables.json");
} else {
  fs.mkdirSync(OUT, { recursive: true });
  for (const [f, css] of Object.entries(files)) fs.writeFileSync(path.join(OUT, f), css);
  console.log(`wrote ${Object.keys(files).map((f) => `tokens/generated/${f}`).join(", ")}`);
}
